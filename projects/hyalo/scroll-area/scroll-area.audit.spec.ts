import { TestBed } from '@angular/core/testing';
import { describe, expect, it, vi } from 'vitest';
import { HyScrollArea } from './scroll-area';
describe('scroll host delegation', () => {
  it('switches listeners and commands to the current viewport and cleans up on destruction', async () => {
    const fixture = TestBed.createComponent(HyScrollArea);
    fixture.componentRef.setInput('label', 'History');
    const first = document.createElement('div');
    const second = document.createElement('div');
    const published = vi.fn();
    fixture.componentInstance.scrolled.subscribe(published);
    fixture.componentRef.setInput('scrollHost', first);
    await fixture.whenStable();
    first.scrollTop = 80;
    first.dispatchEvent(new Event('scroll'));
    expect(published).toHaveBeenCalledWith({ top: 80, left: 0 });
    fixture.componentRef.setInput('scrollHost', second);
    await fixture.whenStable();
    first.dispatchEvent(new Event('scroll'));
    second.scrollTo = vi.fn();
    fixture.componentInstance.scrollTo({ top: 120 });
    expect(second.scrollTo).toHaveBeenCalledWith({ top: 120 });
    fixture.destroy();
    second.dispatchEvent(new Event('scroll'));
    expect(published).toHaveBeenCalledTimes(1);
  });
  it('delegates native scrolling to its own host and reports coordinates', async () => {
    const f = TestBed.createComponent(HyScrollArea);
    f.componentRef.setInput('label', 'History');
    await f.whenStable();
    const host: HTMLElement = f.nativeElement;
    const scroll = vi.fn();
    host.scrollTo = scroll;
    f.componentInstance.scrollTo({ top: 120, left: 20, behavior: 'instant' });
    expect(scroll).toHaveBeenCalledWith({ top: 120, left: 20, behavior: 'instant' });
    host.scrollTop = 120;
    host.scrollLeft = 20;
    const changed = vi.fn();
    f.componentInstance.scrolled.subscribe(changed);
    host.dispatchEvent(new Event('scroll'));
    expect(changed).toHaveBeenCalledWith({ top: 120, left: 20 });
    expect(host.getAttribute('role')).toBe('region');
  });
});
